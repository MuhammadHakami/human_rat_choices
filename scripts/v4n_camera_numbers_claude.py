"""Write paper/wacv2027/camera_numbers.tex (numeric macros only) from the camera-ready analysis, so no number is typed by hand.
  python scripts/v4n_camera_numbers_claude.py
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]; D = ROOT / "data/audit/v4n_camera_ready_20261031"
A = json.loads((D / "analysis.json").read_text()); BC = json.loads((D / "bc_heldout.json").read_text())
M, S, PR = A["means"], A["secondary"], A["primary"]
REG = "registered_sample_source"; PP = 100 / 30
f1 = lambda x: f"{x:.1f}"; pct = lambda x: f"{100 * x:.0f}\\%"


def main():
    sec = lambda fam, m, c="human_bc-human_legal_uniform": S[f"{fam}/{m}/{c}"]
    rv, tr = sec(REG, "revisit_rate"), sec(REG, "trapped")
    allfail = np.mean([M[REG][a]["trapped_share_of_failures"] for a in M[REG]])
    top1 = lambda c: np.mean([M[c][a]["pose_top1"] for a in M[c]])
    mac = dict(HLrevisit=f1(-100 * rv["mean"]), HLrevisitlo=f1(-100 * rv["ci95"][1]), HLrevisithi=f1(-100 * rv["ci95"][0]),
               HLtrap=f1(-100 * tr["mean"]), Ftrap=pct(allfail),
               Bclean=pct(top1(REG)), Bcleanp=f"{np.mean([M[REG][a]['pose_mean_p_true'] for a in M[REG]]):.3f}", Bdim=pct(top1("generality_relit")),
               SAhuman=f"{M[REG]['human_bc']['success'] * PP:.0f}", GRhuman=f"{M['greedy_source']['human_bc']['success'] * PP:.0f}",
               BCrat=pct(BC["rat/trial"]["summary"]["real_acc"]), BChuman=pct(BC["human/trial"]["summary"]["real_acc"]),
               BClegalrat=pct(BC["rat/trial"]["summary"]["legal_uniform_acc"]), BClegalhuman=pct(BC["human/trial"]["summary"]["legal_uniform_acc"]),
               BCinforat=f"{BC['rat/trial']['summary']['choice_content_nats']:.2f}", BCinfohuman=f"{BC['human/trial']['summary']['choice_content_nats']:.2f}")
    T = json.loads((ROOT / "data/unified/tartarus_trajectories.json").read_text())["trials"]; nat = {}
    for t in T:
        c = [tuple(x) for x in t["cells"]]; seen = {c[0]}; rv = 0
        for x in c[1:]: rv += x in seen; seen.add(x)
        nat.setdefault(t["species"], {}).setdefault(t["subject"], []).append(rv / max(len(c) - 1, 1))
    mac.update(NatHum=f"{100 * np.mean([np.mean(v) for v in nat['human'].values()]):.1f}", NatRat=f"{100 * np.mean([np.mean(v) for v in nat['rat'].values()]):.1f}")
    la = A["loop_adjusted"]["registered_sample_source"]
    mac.update(LoopInt=f1(la["intercept_pp"]), LoopIntlo=f1(la["intercept_ci"][0]), LoopInthi=f1(la["intercept_ci"][1]), LoopSlope=f"{-la['slope']:.2f}",
               NoiseTrapH=f"{100 * M['challenge_noisy18']['human_bc']['trapped']:.0f}", CleanTrapH=f"{100 * M[REG]['human_bc']['trapped']:.0f}",
               NoiseTrapL=f"{100 * M['challenge_noisy18']['human_legal_uniform']['trapped']:.0f}", CleanTrapL=f"{100 * M[REG]['human_legal_uniform']['trapped']:.0f}")
    for k0, v in PR.items():                                 # M1-M3, G1 in pp (TeX names: letters only)
        k = dict(M1="MvLegal", M2="MvScratch", M3="MvRat", G1="Greedy")[k0]
        mac[f"P{k}"] = f1(v["mean"] * PP); mac[f"P{k}lo"] = f1(v["ci95"][0] * PP); mac[f"P{k}hi"] = f1(v["ci95"][1] * PP)
        mac[f"P{k}p"] = f"{v['holm_t_p']:.2g}".replace("e-0", "\\times10^{-") + ("}" if "e-0" in f"{v['holm_t_p']:.2g}" else "")
    if "sample_moved" in M:
        for a in M["sample_moved"]: mac[f"MV{a.replace('_', '')}"] = f"{M['sample_moved'][a]['success'] * PP:.1f}"
        mac["MVoldgoalH"] = pct(M["sample_moved"]["human_bc"]["visited_source_goal"]); mac["MVoldgoalL"] = pct(M["sample_moved"]["human_legal_uniform"]["visited_source_goal"])
        try:
            og = sec("sample_moved", "visited_source_goal"); mac["MVoldgoalD"] = f1(100 * og["mean"])
            mt = sec("sample_moved", "trapped"); mac["MVtrapD"] = f1(-100 * mt["mean"])
        except KeyError: pass                                      # partial data
    out = "% generated by scripts/v4n_camera_numbers_claude.py; do not edit\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in mac.items())
    (ROOT / "paper/wacv2027/camera_numbers.tex").write_text(out); print(out)


if __name__ == "__main__":
    main()
